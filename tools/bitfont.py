_BITS = {c: np.array([[ch == "1" for ch in row] for row in rows], bool) for c, rows in _GLYPHS.items()}
W, H, GAP = 5, 7, 1


def width(text, scale=1):
    return max(0, len(text) * (W + GAP) - GAP) * scale


def draw(img, text, x, y, colour, scale=1, shadow=None):
    """Writes `text` into an H x W x C uint8 image in place, its top left corner at (x, y); what
    falls outside is clipped. `shadow`: a colour drawn one pixel down and right first."""
    if shadow is not None:
        draw(img, text, x + scale, y + scale, shadow, scale)
    col = np.asarray(colour, np.uint8)[:img.shape[2]]
    for i, ch in enumerate(str(text).upper()):
        bits = _BITS.get(ch, _BITS["?"])
        if scale > 1:
            bits = np.repeat(np.repeat(bits, scale, 0), scale, 1)
        gx = x + i * (W + GAP) * scale
        y0, x0 = max(0, y), max(0, gx)
        y1, x1 = min(img.shape[0], y + bits.shape[0]), min(img.shape[1], gx + bits.shape[1])
        if y1 <= y0 or x1 <= x0:
            continue
        part = bits[y0 - y:y1 - y, x0 - gx:x1 - gx]
        img[y0:y1, x0:x1][part] = col
    return img
